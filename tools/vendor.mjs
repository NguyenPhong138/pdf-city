// Copies the pinned libraries from node_modules into app/vendor so the app needs no CDN.
// Run after `npm install --ignore-scripts`.
import {cp, mkdir, rm, readFile, writeFile} from 'node:fs/promises';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nm = join(root, 'node_modules');
const out = join(root, 'app', 'vendor');

const files = [
  ['pdf-lib/dist/pdf-lib.min.js', 'pdf-lib.min.js'],
  ['pdf-lib/LICENSE.md', 'licenses/pdf-lib.md'],
  ['@pdf-lib/fontkit/dist/fontkit.umd.min.js', 'fontkit.umd.min.js'],
  ['jszip/dist/jszip.min.js', 'jszip.min.js'],
  ['jszip/LICENSE.markdown', 'licenses/jszip.md'],
  ['pdfjs-dist/build/pdf.min.js', 'pdfjs/pdf.min.js'],
  ['pdfjs-dist/build/pdf.worker.min.js', 'pdfjs/pdf.worker.min.js'],
  ['pdfjs-dist/LICENSE', 'licenses/pdfjs.txt'],
  ['tesseract.js/dist/tesseract.min.js', 'tesseract/tesseract.min.js'],
  ['tesseract.js/dist/worker.min.js', 'tesseract/worker.min.js'],
  ['tesseract.js/LICENSE.md', 'licenses/tesseract.js.md'],
  // OEM 1 (LSTM only) => the worker picks one of these two depending on SIMD support
  ['tesseract.js-core/tesseract-core-simd-lstm.wasm.js', 'tesseract/core/tesseract-core-simd-lstm.wasm.js'],
  ['tesseract.js-core/tesseract-core-lstm.wasm.js', 'tesseract/core/tesseract-core-lstm.wasm.js'],
  ['@tesseract.js-data/vie/4.0.0_best_int/vie.traineddata.gz', 'tesseract/lang/vie.traineddata.gz'],
  ['@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz', 'tesseract/lang/eng.traineddata.gz'],
  ['dejavu-fonts-ttf/ttf/DejaVuSans.ttf', 'fonts/DejaVuSans.ttf'],
  ['dejavu-fonts-ttf/LICENSE', 'licenses/dejavu.txt'],
];
const dirs = [
  ['pdfjs-dist/cmaps', 'pdfjs/cmaps'],
  ['pdfjs-dist/standard_fonts', 'pdfjs/standard_fonts'],
];
// UI faces: only the subsets a Vietnamese page needs
const faces = [
  ['be-vietnam-pro', [400, 500, 700]],
  ['bungee', [400]],
  ['jetbrains-mono', [400, 500]],
];
const SUBSETS = ['vietnamese', 'latin-ext', 'latin'];

await rm(out, {recursive: true, force: true});
for (const [from, to] of files){
  await mkdir(dirname(join(out, to)), {recursive: true});
  await cp(join(nm, from), join(out, to));
}
for (const [from, to] of dirs) await cp(join(nm, from), join(out, to), {recursive: true});

let css = '/* Generated by tools/vendor.mjs from @fontsource packages */\n';
for (const [family, weights] of faces){
  for (const w of weights){
    const src = await readFile(join(nm, '@fontsource', family, `${w}.css`), 'utf8');
    for (const block of src.split(/\n(?=\/\*)/)){
      const name = block.match(/\/\* (\S+) \*\//)?.[1];
      if (!name || !SUBSETS.some(s => name === `${family}-${s}-${w}-normal`)) continue;
      const file = `${name}.woff2`;
      await mkdir(join(out, 'fonts'), {recursive: true});
      await cp(join(nm, '@fontsource', family, 'files', file), join(out, 'fonts', file));
      css += block.replace(/src:[^;]+;/, `src: url(./${file}) format('woff2');`).trim() + '\n\n';
    }
  }
  await cp(join(nm, '@fontsource', family, 'LICENSE'), join(out, 'licenses', `${family}.txt`));
}
await writeFile(join(out, 'fonts', 'fonts.css'), css);
console.log('vendor: copied into', out);
